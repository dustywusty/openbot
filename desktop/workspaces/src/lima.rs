pub fn executable() -> PathBuf {
    for path in [
        "/opt/homebrew/bin/limactl",
        "/usr/local/bin/limactl",
        "/usr/bin/limactl",
    ] {
        if Path::new(path).is_file() {
            return PathBuf::from(path);
        }
    }
    PathBuf::from("limactl")
}

pub fn command(root: &Path, executable: &Path) -> Command {
    let mut command = Command::new(executable);
    let home = std::env::var_os("HOME").unwrap_or_default();
    command
        .env_clear()
        .env("HOME", &home)
        .env(
            "PATH",
            "/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin",
        )
        .env("LIMA_HOME", root.join("vms"))
        .env("TERM", "xterm-256color");
    for key in ["USER", "LOGNAME", "TMPDIR", "LANG"] {
        if let Some(value) = std::env::var_os(key) {
            command.env(key, value);
        }
    }
    command
}

fn image(base: BaseImage, arch: &str) -> Result<(String, &'static str), String> {
    let (image_arch, digest) = match (base, arch) {
        (BaseImage::Debian13, "aarch64") => ("arm64", "sha512:5d3ecec46fd29605db4084388a1e2eb82fd19a80202898f962840ea73793261de721e505e3877c829ae86c37fdd2f6c205b0b3b1337a89d0d4b98d9081adc0c2"),
        (BaseImage::Debian13, "x86_64") => ("amd64", "sha512:d25999de0770d4cde1be72c299ba3ad94eac7ea8fd4d18f8cc86c69df69337e2e8a91d64465a9bfd8f2a78c566fcbcb0842eacc91c09efdef72d719d9f13b535"),
        // Pinned official cloud images from Lima's ubuntu-24.04 image catalogue.
        (BaseImage::Ubuntu2404, "aarch64") => ("arm64", "sha256:50e24e1fb79e89116e939d90aa7738f7af48c442fa1bc2510131e0b39c50348e"),
        (BaseImage::Ubuntu2404, "x86_64") => ("amd64", "sha256:04e8f2461a16a44e78a370284471f29616cdd9baf1893df25807b71f985b6c94"),
        _ => return Err("This VM image requires an ARM64 or x86-64 computer.".into()),
    };
    let url = match base {
        BaseImage::Debian13 => format!("https://cloud.debian.org/images/cloud/trixie/20261103-2651/debian-13-genericcloud-{image_arch}-20261103-2651.qcow2"),
        BaseImage::Ubuntu2404 => format!("https://cloud-images.ubuntu.com/releases/noble/release-20261017/ubuntu-24.04-server-cloudimg-{image_arch}.img"),
    };
    Ok((url, digest))
}

pub fn template(recipe: &Recipe) -> Result<String, String> {
    recipe.validate()?;
    let arch = std::env::consts::ARCH;
    let (image, digest) = image(recipe.base_image, arch)?;
    let mut yaml = format!(
        r#"# Generated by OpenBot. Project storage belongs to this guest.
vmType: vz
arch: {arch}
images:
  - location: "{image}"
    arch: {arch}
    digest: "{digest}"
cpus: {cpus}
memory: "{memory}GiB"
disk: "{disk}GiB"
plain: true
mounts: []
containerd:
  system: false
  user: false
ssh:
  localPort: 0
  forwardAgent: false
  loadDotSSHPubKeys: false
propagateProxyEnv: false
hostResolver:
  enabled: false
networkOpts:
  hostLoopback: false
provision:
  - mode: system
    script: |
      #!/bin/sh
      set -eu
      # Match Lima's Debian template: prevent slow SSH logins caused by vsock LLMNR lookups.
      if command -v resolvectl >/dev/null 2>&1; then
        mkdir -p /etc/systemd/resolved.conf.d
        printf '[Resolve]\nLLMNR=no\n' > /etc/systemd/resolved.conf.d/10-openbot-disable-llmnr.conf
        systemctl restart systemd-resolved.service
      fi
"#,
        cpus = recipe.resources.cpus,
        memory = recipe.resources.memory_gib,
        disk = recipe.resources.disk_gib
    );
    if !recipe.ports.is_empty() {
        yaml.push_str("portForwards:\n");
        for port in &recipe.ports {
            yaml.push_str(&format!("  - guestIP: 127.0.0.1\n    guestPort: {}\n    hostIP: 127.0.0.1\n    hostPort: {}\n    proto: tcp\n    static: true\n", port.guest, port.host));
        }
    }
    Ok(yaml)
}

pub fn shell_args(id: &str) -> Vec<OsString> {
    [
        "shell",
        "--preserve-env=false",
        "--workdir=/workspace/project",
        id,
        "--",
    ]
    .map(OsString::from)
    .to_vec()
}

#[cfg(test)]
mod image_tests {
    use super::*;

    #[test]
    fn supported_images_pin_official_host_architecture_downloads() {
        for arch in ["aarch64", "x86_64"] {
            let expected_arch = if arch == "aarch64" { "arm64" } else { "amd64" };
            let (debian_url, debian_hash) = image(BaseImage::Debian13, arch).unwrap();
            assert!(debian_url
                .starts_with("https://cloud.debian.org/images/cloud/trixie/20261103-2651/"));
            assert!(debian_url.contains(expected_arch));
            assert_eq!(debian_hash.strip_prefix("sha512:").unwrap().len(), 128);
            let (ubuntu_url, ubuntu_hash) = image(BaseImage::Ubuntu2404, arch).unwrap();
            assert!(ubuntu_url
                .starts_with("https://cloud-images.ubuntu.com/releases/noble/release-20261017/"));
            assert!(ubuntu_url.contains(expected_arch));
            assert_eq!(ubuntu_hash.strip_prefix("sha256:").unwrap().len(), 64);
        }
        assert!(image(BaseImage::Debian13, "riscv64").is_err());
    }

    #[test]
    fn selecting_ubuntu_preserves_vm_isolation_and_preview_controls() {
        let recipe = Recipe::for_image(BaseImage::Ubuntu2404);
        let config = template(&recipe).unwrap();
        assert!(config.contains("ubuntu-24.04-server-cloudimg"));
        assert!(!config.contains("cloud.debian.org"));
        for setting in [
            "mounts: []",
            "forwardAgent: false",
            "loadDotSSHPubKeys: false",
            "propagateProxyEnv: false",
            "hostLoopback: false",
            "hostIP: 127.0.0.1",
        ] {
            assert!(config.contains(setting), "missing {setting}");
        }
    }
}

/// Stream stdout and stderr from a single child. Setup output stays in the workspace log.
pub fn run(
    mut command: Command,
    input: Option<&str>,
    workspace_id: &str,
    stage: &str,
    emit: &mut impl FnMut(Event),
) -> Result<(), String> {
    command
        .stdin(if input.is_some() {
            Stdio::piped()
        } else {
            Stdio::null()
        })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = command
        .spawn()
        .map_err(|error| format!("Could not start workspace operation: {error}"))?;
    let writer = if let Some(input) = input {
        let mut stdin = child
            .stdin
            .take()
            .ok_or("Workspace input is unavailable.")?;
        let bytes = input.as_bytes().to_vec();
        Some(thread::spawn(move || stdin.write_all(&bytes)))
    } else {
        None
    };
    let (sender, receiver) = mpsc::sync_channel(64);
    let read = |pipe: Box<dyn Read + Send>, sender: mpsc::SyncSender<String>| {
        thread::spawn(move || {
            // Bound each line. A tool must not pin unbounded host memory with one line of output.
            let mut reader = BufReader::new(pipe);
            loop {
                let mut bytes = Vec::new();
                match reader
                    .by_ref()
                    .take(64 * 1024)
                    .read_until(b'\n', &mut bytes)
                {
                    Ok(0) | Err(_) => break,
                    Ok(_) => {
                        if sender
                            .send(String::from_utf8_lossy(&bytes).trim_end().to_owned())
                            .is_err()
                        {
                            break;
                        }
                    }
                }
            }
        })
    };
    let stdout = read(
        Box::new(
            child
                .stdout
                .take()
                .ok_or("Workspace output is unavailable.")?,
        ),
        sender.clone(),
    );
    let stderr = read(
        Box::new(
            child
                .stderr
                .take()
                .ok_or("Workspace error output is unavailable.")?,
        ),
        sender,
    );
    let mut tail = String::new();
    for line in receiver {
        if !line.is_empty() {
            tail = line.clone();
            emit(Event {
                workspace_id: workspace_id.into(),
                stage: stage.into(),
                message: line,
            });
        }
    }
    let status = child.wait().map_err(|error| error.to_string())?;
    let _ = stdout.join();
    let _ = stderr.join();
    if let Some(writer) = writer {
        let _ = writer.join();
    }
    if status.success() {
        Ok(())
    } else {
        Err(format!("Workspace step {stage} stopped ({status}). {tail}"))
    }
}
